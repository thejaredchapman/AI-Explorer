// Use-case atlas data. Each entry is [title, riskFlags]. The safety grade is computed from the flags (see GRADING below),
// so the grade is never stored and can be audited. Grades are a planning aid, not a certification.

export const RISK_FLAGS = {
  H: { name: 'High stakes', weight: 2, desc: "A wrong answer could harm someone's health, money, rights or liberty.", guardrail: "A qualified human makes the decision. Treat Claude's output as advice, never the verdict." },
  S: { name: 'Safety-critical', weight: 2, desc: 'Touches physical systems, equipment or infrastructure where failure injures people or damages assets.', guardrail: 'Keep Claude out of the control loop. A qualified engineer approves every change and a fail-safe exists.' },
  C: { name: 'Dual-use', weight: 2, desc: 'Cyber or biology work that could help attackers as well as defenders.', guardrail: "Fable 5.2 may block or reroute this to an Opus model. Verified defensive teams use Mythos 5.2 through a verification program." },
  P: { name: 'Personal data', weight: 1, desc: 'Handles personal, health, financial or student information.', guardrail: 'Share the minimum, mask identifiers, confirm retention and consent, and log who saw what.' },
  R: { name: 'Regulated', weight: 1, desc: 'Sits under law, licensing or audit requirements.', guardrail: 'Check the rules for your jurisdiction, keep an audit trail, and have a responsible professional own the output.' },
  X: { name: 'Acts on its own', weight: 1, desc: 'Sends, publishes, buys or executes without a person approving each step.', guardrail: 'Limit permissions, add an approval step before anything irreversible, and monitor what it did.' },
};
export const FLAG_ORDER = ['H', 'S', 'C', 'P', 'R', 'X'];

export const GRADES = {
  A: { name: 'Light touch', oversight: 'Skim before you use it. Low risk if it is wrong.' },
  B: { name: 'Spot-check', oversight: 'Check key facts and sample outputs. One risk factor to manage.' },
  C: { name: 'Review required', oversight: 'A qualified person reviews every output before it is used.' },
  D: { name: 'Expert gate', oversight: 'Do not automate. Needs expert sign-off, strong controls and an audit trail, or should not be done with AI at all.' },
};

export const scoreOf = (flags) => flags.split('').reduce((a, c) => a + (RISK_FLAGS[c] ? RISK_FLAGS[c].weight : 0), 0);
export const gradeOf = (flags) => { const s = scoreOf(flags); return s === 0 ? 'A' : s === 1 ? 'B' : s <= 3 ? 'C' : 'D'; };

